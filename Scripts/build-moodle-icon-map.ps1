[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$iconRoot = Join-Path $repoRoot 'third-party-assets\moodle-icons'
$ownIconRoot = Join-Path $repoRoot 'assets\moodle-icons'
$rendererPath = Join-Path $repoRoot '42\media\web\expanded-needs.js'
$startMarker = '/* GENERATED_MOODLE_ICONS_START */'
$endMarker = '/* GENERATED_MOODLE_ICONS_END */'

if (-not (Test-Path -LiteralPath $iconRoot -PathType Container)) {
    throw "Moodle icon source directory is missing: $iconRoot"
}

$entries = [Collections.Generic.List[string]]::new()
foreach ($root in @($iconRoot, $ownIconRoot)) {
Get-ChildItem -LiteralPath $root -Recurse -File -Filter '*.png' |
    Sort-Object FullName |
    ForEach-Object {
        $relative = $_.FullName.Substring($root.Length + 1)
        $key = [IO.Path]::ChangeExtension($relative, $null).TrimEnd('.').Replace('\', '/')
        $base64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($_.FullName))
        # Imported filenames are restricted to our committed asset tree and
        # contain no quotes. Base64 contains no JSON-sensitive characters.
        if ($key.Contains('"')) {
            throw "Unsupported quote in moodle icon key: $key"
        }
        $entries.Add("    `"$key`": `"data:image/png;base64,$base64`"")
    }
}

$generated = @(
    $startMarker
    '// Generated by scripts/build-moodle-icon-map.ps1 from the committed PNGs.'
    '// Do not edit this block by hand.'
    'const PZ_PULSE_EXPANDED_MOODLE_ICONS = {'
    ($entries -join ",`n")
    '};'
    $endMarker
) -join "`n"

$renderer = [IO.File]::ReadAllText($rendererPath)
$pattern = [Regex]::Escape($startMarker) + '[\s\S]*?' + [Regex]::Escape($endMarker)
if (-not [Regex]::IsMatch($renderer, $pattern)) {
    throw "Generated icon markers are missing from $rendererPath"
}

$updated = [Regex]::Replace($renderer, $pattern, [Text.RegularExpressions.MatchEvaluator]{ param($match) $generated }, 1)
[IO.File]::WriteAllText($rendererPath, $updated, [Text.UTF8Encoding]::new($false))

Write-Output "Embedded $($entries.Count) PNG moodle glyphs in $rendererPath"
